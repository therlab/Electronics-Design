/**
 * @file    config.h
 * @brief   所有可调参数集中在这里，改完 Rebuild 就生效
 */

#ifndef CONFIG_H
#define CONFIG_H

/* ================================================================
 * 1. 基础速度 (PWM 值, 范围 0~1000)
 * ================================================================ */
#define BASE_SPEED      350     /* 前进基础速度 */

/* ================================================================
 * 2. 灰度循迹 PID
 *    Kp越大转弯越猛，Kd越大越稳但反应变慢，Ki一般不需要
 * ================================================================ */
#define GRAY_KP         2.5f    /* 灰度比例 P：权重已翻倍，KP恢复到原值 */
#define GRAY_KI         0.0f    /* 灰度积分 I：一般设0 */
#define GRAY_KD         0.8f    /* 灰度微分 D */
#define GRAY_INT_MAX    500.0f  /* 积分限幅 */

/* 8路灰度传感器权重 (G1最左 ~ G8最右)，绝对值越大越灵敏 */
#define GRAY_W1   -210          /* 第1路(最左边) */
#define GRAY_W2   -150          /* 第2路 */
#define GRAY_W3   -90          /* 第3路 */
#define GRAY_W4    -50          /* 第4路 */
#define GRAY_W5     50          /* 第5路 */
#define GRAY_W6    90          /* 第6路 */
#define GRAY_W7    150          /* 第7路 */
#define GRAY_W8    210          /* 第8路(最右边) */

/* ================================================================
 * 3. 陀螺仪直走 PD (模式2)
 * ================================================================ */
#define YAW_KP          6.0f    /* 航向比例 P */
#define YAW_KI          0.05f   /* 航向积分 I：加大加速收敛 */
#define YAW_KD          0.5f    /* 航向微分 D */
#define YAW_INT_MAX     350.0f  /* 航向积分限幅 */

/* ================================================================
 * 4. 陀螺仪转弯 PID (两段式: 粗调+精调)
 *    误差>20度: 猛转快速接近目标
 *    误差<20度: 精细PID慢速对准
 *    误差<3度且稳定: 退出
 * ================================================================ */
#define TURN_KP_COARSE   3.8f    /* 粗调 P */
#define TURN_KI_COARSE   0.01f    /* 粗调 I：关掉 */
#define TURN_KD_COARSE   1.5f    /* 粗调 D */
#define TURN_SPD_COARSE  400.0f  /* 粗调最低马力 */
#define TURN_INT_MAX     800.0f  /* 积分限幅 */

#define TURN_KP_FINE     1.0f    /* 精调 P */
#define TURN_KI_FINE     0.0f    /* 精调 I：关掉，避免末端积分抖 */
#define TURN_KD_FINE     0.6f    /* 精调 D */
#define TURN_SPD_FINE    190.0f   /* 精调最低马力：降下来末端就不抖了 */

#define TURN_SWITCH_DEG  20.0f   /* 超过这个角度用粗调，低于用精调 */
#define TURN_MIN_ERROR   1.50f    /* 退出阈值(度)：放宽提前收工 */
#define TURN_EXIT_CNT    3       /* 连续N次低于阈值退出 */
#define TURN_TIMEOUT_MS  2500    /* 超时(毫秒) */

#define TURN_FWD_BIAS   -10     /* 转弯前后偏置: 负=往后拉, 正=往前推 */
#define TURN_LR_COMP     50     /* 转弯左右补偿: 正=轴心左移, 负=轴心右移 */
#define TURN_90         90.0f   /* 90度转弯目标角度 */
#define TURN_180        180.0f  /* 180度转弯目标角度 */

/* ================================================================
 * 5. 编码器速度 PI (左右轮各一个)
 * ================================================================ */
#define SPEED_KP        0.0f    /* 速度比例 P：暂关，需标定 PWM↔编码器 换算关系后重开 */
#define SPEED_KI        0.0f    /* 速度积分 I：暂关，否则量纲不匹配导致积分器饱和 */
#define SPEED_INT_MAX   500.0f  /* 速度积分限幅 */

/* ================================================================
 * 6. 丢线恢复 (8路全黑时原地旋转找线)
 * ================================================================ */
#define LOST_LINE_SPEED 500.0f  /* 丢线旋转力度 */

/* ================================================================
 * 7. OLED 刷新频率
 * ================================================================ */
#define OLED_DIV        10      /* 每N个主循环刷新一次OLED */

/* ================================================================
 * 8. 自动转弯检测 (模式1灰度循迹中)
 * ================================================================ */
#define AUTO_TURN_ON_WG7_G8_BLACK
#define AUTO_TURN_DEBOUNCE  1   /* 连续N次确认后才触发转弯 */

/* ================================================================
 * 9. 编码器测距
 * ================================================================ */
#define MM_PER_COUNT   10.53f   /* 每脉冲对应毫米 (实测校准) */
#define WHEEL_DIA_MM    67.0f   /* 轮径(mm) */

/* ================================================================
 * 10. 路线规划 (模式1自动跑)
 *     每段: 灰度循迹走距离 -> 陀螺仪直走等色标 -> 拐弯90度
 *     距离单位mm, 需实测校准
 * ================================================================ */
#define GRAY_DIST_MM    850     /* 灰度循迹段距离(mm), 走完后切陀螺仪 */
#define GYRO_SPEED      180     /* 陀螺仪直走速度(PWM) */
#define BACK_DIST_MM    150      /* 检测色标后倒退距离(mm) */


/* 各段直走时用的陀螺仪 PID (调这个) */
#define ROUTE_YAW_KP    6.0
#define ROUTE_YAW_KD    0.5f

/* ================================================================
 * 11. 主循环周期
 * ================================================================ */
#define LOOP_DELAY_MS   5       /* 主循环延时(毫秒) */

#endif /* CONFIG_H */
